import ee.ria.xroad.common.identifier.ClientId;

import java.util.List;

/**
 * Parsed response of a member DID registration request.
 *
 * @param requestId request id in the central server database, null if missing
 * @param results   one result per request entry, in request order
 */
public record MemberDidRegResponse(Integer requestId, List<Result> results) {

    public MemberDidRegResponse {
        results = List.copyOf(results);
    }

    public record Result(ClientId member, String status, String reason) {
    }
}
