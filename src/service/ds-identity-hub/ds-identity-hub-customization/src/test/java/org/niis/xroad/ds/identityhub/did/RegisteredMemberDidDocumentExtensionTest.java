package org.niis.xroad.ds.identityhub.did;

import org.eclipse.edc.spi.monitor.Monitor;
import org.eclipse.edc.spi.system.ServiceExtensionContext;
import org.eclipse.edc.web.spi.WebService;
import org.eclipse.edc.web.spi.configuration.PortMappingRegistry;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.niis.xroad.globalconf.GlobalConfProvider;

import java.lang.reflect.Field;

import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.ArgumentMatchers.isA;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

@ExtendWith(MockitoExtension.class)
class RegisteredMemberDidDocumentExtensionTest {

    @Mock
    private WebService webService;
    @Mock
    private PortMappingRegistry portMappingRegistry;
    @Mock
    private GlobalConfProvider globalConfProvider;
    @Mock
    private ServiceExtensionContext context;
    @Mock
    private Monitor monitor;

    @Test
    void registersTheFilterOnTheDidWebContext() throws Exception {
        when(context.getMonitor()).thenReturn(monitor);
        var extension = new RegisteredMemberDidDocumentExtension();
        inject(extension, "webService", webService);
        inject(extension, "portMappingRegistry", portMappingRegistry);
        inject(extension, "globalConfProvider", globalConfProvider);

        extension.initialize(context);

        verify(webService).registerResource(eq("did"), isA(RegisteredMemberDidDocumentFilter.class));
    }

    private static void inject(Object target, String fieldName, Object value) throws Exception {
        Field field = target.getClass().getDeclaredField(fieldName);
        field.setAccessible(true);
        field.set(target, value);
    }
}
